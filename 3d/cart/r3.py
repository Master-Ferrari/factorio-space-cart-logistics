# -*- coding: utf-8 -*-
"""Раунд 3 блокинга: силуэт-механизм, рифмующийся с рельсом.

Правила раунда (см. README):
  * Контакт с рельсом — только в центральной зоне |y| < 0.15: на повороте r 0.5 лезвие
    под концами каретки уходит вбок на 0.16 (при y = 0.37). Там низ каретки должен быть
    выше лезвия (z > 0.12) или над раструбом TUNNEL. В центре стоит бежевый разрезной
    ложемент, как на тайле (внутри него ролики ±45°).
  * Рифмы с тайлом: светлые стальные дуги-лезвия, стрельчатые наконечники, четырёхлучевая
    звезда, бежевые ложементы, октагоны в рамке, латунные втулки.
  * Значения: тёмная масса корпуса (выделяется на светлом рельсе), светлые лезвия и рамы,
    бежевый и латунь — акценты.
  * Лоуполи: плоская фигура → выдавливание → срезы плоскостями → фаска в один сегмент.
"""

import math

from mathutils import Vector

import scl3d as K
import lowpoly as L

D90 = L.D90
CH = 0.008                 # стандартная фаска

# раструб-тоннель под лезвием: узкий в центре, к концам расходится под вынос лезвия на повороте
TUNNEL = [(-0.20, -0.43), (0.20, -0.43), (0.05, -0.12), (0.05, 0.12), (0.20, 0.43), (-0.20, 0.43),
          (-0.05, 0.12), (-0.05, -0.12)]


def flare(obj, c, root, zt=0.135):
    K.bool_cut(obj, L.plan("flare_cut", c, TUNNEL, -0.1, zt, None, root))


def lancet(W, z0, H, n=4):
    """Полуарка стрельчатого свода: от пяты (W, z0) к острию (0, H), центр дуги — на (-c, z0)."""
    h = H - z0
    cc = (h * h - W * W) / (2 * W)
    R = W + cc
    at = math.atan2(h, cc)
    return [(-cc + R * math.cos(at * i / n), z0 + R * math.sin(at * i / n)) for i in range(n + 1)]


def arch(W, z0, H, n=4):
    """Полная стрельчатая арка (x, z): от правой пяты через острие к левой."""
    half = lancet(W, z0, H, n)
    return half + [(-x, z) for x, z in reversed(half[:-1])]


def grow(cuts, off):
    """Сдвинуть плоскости срезов наружу на off (для бандажей и накладок поверх корпуса)."""
    out = []
    for co, no in cuts:
        n = Vector(no).normalized()
        out.append((tuple(Vector(co) + n * off), no))
    return out


def cradle(c, root, M, hy=0.12, z1=0.14, hw=0.15, gap=0.03, name="cradle"):
    """Бежевый разрезной ложемент над лезвием — точка опоры на рельс (ролики ±45° внутри)."""
    for s in (-1, 1):
        x0, x1 = sorted((s * gap, s * hw))
        L.plan("%s%+d" % (name, s), c, L.rect(x0, x1, -hy, hy), 0.0, z1, M["beige"], root,
               cuts=[((s * hw, 0, z1 - 0.035), (s * 1, 0, 1.0))], ch=CH)


def ring_segments(name, c, outer, inner, z0, z1, mat, root, ch=0.0):
    """Кольцо-рама из трапеций между двумя многоугольниками с одинаковым числом вершин."""
    n = len(outer)
    for i in range(n):
        j = (i + 1) % n
        L.plan("%s%02d" % (name, i), c, [outer[i], outer[j], inner[j], inner[i]], z0, z1, mat, root, ch=ch)


# ── T1: клещи ────────────────────────────────────────────────────────
def build_t1(c, root, M):
    """Две светлые челюсти-лезвия (дуги со стрельчатыми кончиками, как лезвия тайла) сходятся
    на латунном шарнире сзади и обнимают восьмигранный контейнер; кончики заходят друг за
    друга, как ножницы. Сзади — гидроцилиндр, сводящий клещи. Ложемент под центром."""
    cradle(c, root, M, hy=0.11, z1=0.14, hw=0.14)
    L.plan("chassis", c, L.octagon(0.15, 0.20, 0.06), 0.12, 0.17, M["dark"], root, ch=CH)
    L.plan("spine", c, L.rect(-0.05, 0.05, -0.37, -0.10), 0.13, 0.20, M["dark"], root, ch=CH)
    L.plan("can", c, L.ngon(0.18, 8, rot=math.pi / 8, c=(0, 0.0)), 0.15, 0.265, M["mid"], root, ch=0.012)
    L.plan("can_lid", c, L.ngon(0.11, 8, rot=math.pi / 8, c=(0, 0.0)), 0.26, 0.28, M["beige"], root, ch=0.005)
    for s in (-1, 1):                                         # клещи раскрыты: кончики загнуты внутрь, зазор спереди
        jaw = L.sickle((s * 0.035, -0.33), (s * 0.285, -0.02), (s * 0.085, 0.365), 0.075, n=11, w1=0.085, w2=0.0)
        L.plan("jaw%+d" % s, c, jaw, 0.16, 0.23, M["light"], root, ch=0.012)
        L.plan("pad%+d" % s, c, L.rect(*sorted((s * 0.17, s * 0.225)), -0.07, 0.07), 0.16, 0.235, M["beige"], root,
               ch=0.005)
    L.disc("hinge", c, 0.055, 0.17, (0, -0.33, 0.225), 'Z', M["brass"], root, segs=8, ch=0.005)
    L.rod("ram", c, (0.0, -0.37, 0.17), (0.0, -0.20, 0.17), 0.03, M["dark"], root, segs=6)


# ── T2: валик ────────────────────────────────────────────────────────
def build_t2(c, root, M):
    """«Одно большое колесо»: поперёк каретки лежит валик, ручьём посередине он катится по
    лезвию. Это единственная опора, и она в центре — поворот r 0.5 ей не мешает. Сбоку виден
    торец валика — одно большое колесо; в составе — ряд колёс. Спереди и сзади на раскосах
    к оси валика висят узкие стрельчатые бункеры: в плане — крест (валик поперёк, носы вдоль)."""
    rg, r = 0.08, 0.118                     # корень ручья и радиус валика
    zc = K.RAIL_TOP_Z + rg
    for s in (-1, 1):
        L.disc("roll%+d" % s, c, r, 0.21, (s * 0.135, 0, zc), 'X', M["light"], root, segs=12, ch=0.008)
        L.disc("tyre%+d" % s, c, r + 0.008, 0.035, (s * 0.215, 0, zc), 'X', M["mid"], root, segs=12, ch=0.004)
        L.disc("hubcap%+d" % s, c, 0.05, 0.06, (s * 0.26, 0, zc), 'X', M["brass"], root, segs=8, ch=0.004)
        for sy in (-1, 1):                                  # тяги-раскосы: бункеры висят на оси валика
            L.rod("link%+d%+d" % (s, sy), c, (s * 0.15, sy * 0.17, 0.215), (s * 0.27, 0, zc), 0.022,
                  M["dark"], root, segs=6)
    L.disc("groove", c, rg, 0.04, (0, 0, zc), 'X', M["dark"], root, segs=12)
    L.plan("spine", c, L.rect(-0.045, 0.045, -0.17, 0.17), 0.30, 0.335, M["dark"], root, ch=0.006)
    for sy in (-1, 1):
        y0, tip = 0.135, 0.375
        pts = [(-0.17, y0), (0.17, y0), (0.15, 0.27), (0.0, tip), (-0.15, 0.27)]
        pts = [(x, sy * y) for x, y in pts]
        L.plan("bin%+d" % sy, c, pts, 0.13, 0.30, M["mid"], root,
               cuts=[((0, sy * tip, 0.15), (0, sy, 0.8)), ((0.17, 0, 0.20), (1, 0, 0.9)),
                     ((-0.17, 0, 0.20), (-1, 0, 0.9))], ch=CH)
        L.plan("lid%+d" % sy, c, [(x * 0.55, sy * (0.15 + (abs(y) - 0.135) * 0.55)) for x, y in pts], 0.28, 0.30,
               M["beige"], root, ch=0.004)


# ── T3: шеврон ───────────────────────────────────────────────────────
def chevron_cuts():
    return [
        ((0.33, 0, 0.04), (1, 0, 1.25)), ((-0.33, 0, 0.04), (-1, 0, 1.25)),     # скаты, конёк 0.30
        ((0, 0.37, 0.12), (0.55, 1, 1.1)), ((0, 0.37, 0.12), (-0.55, 1, 1.1)),   # гранёный нос
        ((0, -0.21, 0.26), (0, -1, 1.2)),                                       # тыльный скат к вырезу
        ((0, 0, 0.30), (0, 0, 1)),
    ]


def build_t3(c, root, M):
    """Гранёный наконечник: острый нос вперёд, хвост с вогнутым вырезом-ласточкой (дуга
    как у лезвия). В поезде шевроны входят друг в друга — состав читается направлением.
    Скаты стоят на ложе, под коньком — раструб под лезвие. Конёк — светлое лезвие,
    поперёк — бежевый бандаж, в вырезе — гидроцилиндры."""
    pts = [(0, 0.37), (0.33, 0.02), (0.30, -0.36)]
    pts += L.arc3((0.30, -0.36), (0, -0.19), (-0.30, -0.36), 7)[1:-1]
    pts += [(-0.30, -0.36), (-0.33, 0.02)]
    hull = L.plan("hull", c, pts, 0.0, 0.5, M["mid"], root, cuts=chevron_cuts(), ch=CH)
    flare(hull, c, root)
    band = L.plan("band", c, pts, 0.0, 0.5, M["beige"], root,
                  cuts=grow(chevron_cuts(), 0.016) + [((0, -0.03, 0), (0, 1, 0)), ((0, -0.10, 0), (0, -1, 0))],
                  ch=CH)
    flare(band, c, root)
    L.plan("ridge", c, [(x, y + 0.08) for x, y in L.lens(0.58, 0.07, 7)], 0.0, 0.5, M["light"], root,
           cuts=grow(chevron_cuts(), 0.014), ch=0.004)
    for s in (-1, 1):
        L.disc("tail%+d" % s, c, 0.035, 0.07, (s * 0.255, -0.31, 0.105), 'Z', M["brass"], root, segs=8, ch=0.004)
        L.rod("ram%+d" % s, c, (s * 0.235, -0.30, 0.15), (s * 0.05, -0.20, 0.25), 0.024, M["dark"], root, segs=6)
        L.rod("rod%+d" % s, c, (s * 0.12, -0.24, 0.21), (s * 0.05, -0.20, 0.25), 0.013, M["light"], root, segs=6)
    L.disc("dome", c, 0.045, 0.03, (0.0, -0.17, 0.27), 'Y', M["brass"], root, segs=8)
    L.plate("visor_l", c, L.rect(-0.06, 0.06, -0.02, 0.02), 0.0, 0.012, M["accent"], root,
            origin=(0.10, 0.25, 0.16), U=(-1, 0.55, 0), V=(0, -0.6, 1))
    L.plate("visor_r", c, L.rect(-0.06, 0.06, -0.02, 0.02), 0.0, 0.012, M["accent"], root,
            origin=(-0.10, 0.25, 0.16), U=(-1, -0.55, 0), V=(0, -0.6, 1))


# ── T4: барабан ─────────────────────────────────────────────────────
def build_t4(c, root, M):
    """Карусель-барабан на поворотной тележке: «одно колесо» — горизонтальный круг, который
    на поворотах не цепляет соседей. Сверху — звезда тайла: четыре вогнутые дуги делят
    барабан на четыре кармана-слота (как тёмные карманы по углам тайла)."""
    cradle(c, root, M, hy=0.12, z1=0.14, hw=0.15)
    L.plan("chassis", c, L.octagon(0.16, 0.22, 0.07), 0.125, 0.16, M["dark"], root, ch=CH)
    R = 0.275
    out = L.ngon(R, 16, rot=math.pi / 16)
    L.plan("drum", c, out, 0.15, 0.20, M["dark"], root, ch=CH)
    ring_segments("rim", c, out, [(x * 0.82, y * 0.82) for x, y in out], 0.20, 0.24, M["mid"], root)
    # звезда тайла: лучи выходят за обод (силуэт «круг + 4 острия»), передний и задний — сцепки
    L.plan("star", c, L.concave_star(0.34, 0.375, 0.17, n=4), 0.17, 0.28, M["light"], root,
           cuts=[((0, 0, 0.28), (0.3, 0.3, 1)), ((0, 0, 0.28), (-0.3, 0.3, 1)),
                 ((0, 0, 0.28), (0.3, -0.3, 1)), ((0, 0, 0.28), (-0.3, -0.3, 1)),
                 ((0, 0.375, 0.17), (0, 1, 0.6)), ((0, -0.375, 0.17), (0, -1, 0.6)),
                 ((0.34, 0, 0.17), (1, 0, 0.6)), ((-0.34, 0, 0.17), (-1, 0, 0.6))], ch=0.004)
    L.disc("hub", c, 0.05, 0.03, (0, 0, 0.285), 'Z', M["brass"], root, segs=8, ch=0.004)
    # привод индексации — латунный мотор в заднем правом кармане
    L.disc("motor", c, 0.05, 0.07, (0.15, -0.15, 0.235), 'Z', M["brass"], root, segs=8, ch=0.004)
    L.disc("motor_cap", c, 0.03, 0.02, (0.15, -0.15, 0.275), 'Z', M["accent"], root, segs=8)


# ── T5: телескоп ─────────────────────────────────────────────────────
def build_t5(c, root, M):
    """Телескопический кожух: четыре арки стрельчатого сечения вдвигаются друг в друга
    к носу (как кожух направляющих станка). По коньку — длинный гидроцилиндр, который его
    раздвигает. Самая большая, задняя арка — бежевая, как ложемент тайла."""
    segs = [(-0.37, -0.14, 0.31, 0.30, "beige"), (-0.19, 0.03, 0.265, 0.27, "mid"),
            (-0.02, 0.19, 0.215, 0.24, "mid"), (0.14, 0.31, 0.165, 0.21, "mid")]
    for i, (y0, y1, W, H, m) in enumerate(segs):
        half = lancet(W, 0.0, H, n=4)
        prof = [(0.045, 0.0)] + half[:-1] + [(0.0, H), (0.0, 0.14), (0.045, 0.14)]
        for s in (-1, 1):
            pp = [(s * x, z) for x, z in prof]
            if s < 0:
                pp = pp[::-1]
            o = L.section("shell%d%+d" % (i, s), c, pp, y0, y1, M[m], root, ch=CH)
            flare(o, c, root, 0.14)
        outer = arch(W + 0.012, 0.0, H + 0.012)            # светлый обруч на переднем крае арки
        inner = arch(W - 0.035, 0.0, H - 0.035)
        o = L.section("hoop%d" % i, c, outer + inner[::-1], y1 - 0.025, y1, M["light"], root)
        flare(o, c, root, 0.14)
    L.plan("nose", c, [(-0.10, 0.30), (0.10, 0.30), (0.0, 0.375)], 0.10, 0.20, M["dark"], root,
           cuts=[((0, 0.30, 0.20), (0, 1, 1.2))], ch=0.006)
    L.rod("ram", c, (0.0, -0.30, 0.335), (0.0, 0.05, 0.30), 0.03, M["dark"], root, segs=6)
    L.rod("ram_rod", c, (0.0, 0.0, 0.30), (0.0, 0.30, 0.245), 0.016, M["light"], root, segs=6)
    L.disc("ram_eye", c, 0.03, 0.08, (0.0, -0.32, 0.34), 'X', M["brass"], root, segs=8)
    L.disc("ram_eye2", c, 0.025, 0.07, (0.0, 0.31, 0.24), 'X', M["brass"], root, segs=8)
    cradle(c, root, M, hy=0.10, z1=0.14, hw=0.12)


# ── T6: грейфер ──────────────────────────────────────────────────────
def build_t6(c, root, M):
    """Корпус — двухчелюстной грейфер-миндалина: в сечении стрельчатая арка, в плане линза
    с острыми концами. Челюсти губами стоят на ложе по обе стороны лезвия, к концам
    подбираются над лезвием. Латунная ось челюстей — по коньку."""
    hw_max, Lh = 0.29, 0.37
    R = (hw_max ** 2 + Lh ** 2) / (2 * hw_max)
    rings = []
    for y in (-0.37, -0.31, -0.20, 0.0, 0.20, 0.31, 0.37):
        hw = max(math.sqrt(max(R * R - y * y, 0)) - (R - hw_max), 0.02)
        z0 = 0.0 if abs(y) <= 0.2 else 0.135 * (abs(y) - 0.2) / 0.17
        H = 0.165 + 0.135 * (hw / hw_max)
        rings.append([(x, y, z) for x, z in arch(hw, z0, H, n=3)])
    hull = L.loft("hull", c, rings, M["mid"], root, ch=CH)
    flare(hull, c, root, 0.15)
    L.plan("seam", c, L.lens(0.66, 0.035, 5), 0.20, 0.305, M["dark"], root)
    L.disc("pivot", c, 0.032, 0.36, (0, 0, 0.30), 'Y', M["brass"], root, segs=8, ch=0.004)
    for sy in (-1, 1):                                    # ось выходит за кончики штырями-сцепками
        L.rod("pin%+d" % sy, c, (0, sy * 0.18, 0.30), (0, sy * 0.37, 0.205), 0.022, M["light"], root, segs=6)
        L.disc("pin_eye%+d" % sy, c, 0.03, 0.05, (0, sy * 0.355, 0.21), 'X', M["brass"], root, segs=8)
    for s in (-1, 1):
        L.plan("lip%+d" % s, c, L.lens(0.40, 0.10, 5), 0.0, 0.05, M["beige"], root, ch=CH).location.x = s * 0.255
    cradle(c, root, M, hy=0.10, z1=0.15, hw=0.12)


BUILDERS = dict(r3_tongs=build_t1, r3_roller=build_t2, r3_chevron=build_t3, r3_drum=build_t4,
                r3_telescope=build_t5, r3_grab=build_t6)
